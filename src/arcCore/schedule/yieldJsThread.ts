// JS 스레드 양보 — 부트 후속 무거운 패스(catch-up·일일 배치·영토전 probe)를
// 한 덩어리 동기 실행 대신 조각(chunk) 사이에 이벤트 루프를 비워,
// 타이틀 버튼 탭 등 사용자 입력이 즉시 처리되게 한다.
// (2026-07-19 타이틀 「탭 후 2~3초 무반응」 근본 조치 — 매크로태스크 경계 필수:
//  Promise.resolve()/미세태스크는 터치 이벤트를 끼워주지 못한다.)
// ============================================================

export function yieldJsThread(): Promise<void> {
  return new Promise<void>((resolve) => {
    setTimeout(resolve, 0);
  });
}
