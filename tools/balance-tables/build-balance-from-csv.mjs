import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(process.cwd());
const TABLE_DIR = resolve(ROOT, 'tables', 'balance');
const OUT_DIR = resolve(ROOT, 'src', 'data', 'balance', 'generated');

function parseCsv(text) {
  const rows = [];
  let i = 0;
  let field = '';
  let row = [];
  let inQuotes = false;
  while (i < text.length) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 2;
          continue;
        }
        inQuotes = false;
      } else field += ch;
      i += 1;
      continue;
    }
    if (ch === '"') {
      inQuotes = true;
      i += 1;
      continue;
    }
    if (ch === ',') {
      row.push(field);
      field = '';
      i += 1;
      continue;
    }
    if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field);
      field = '';
      rows.push(row);
      row = [];
      i += 1;
      continue;
    }
    field += ch;
    i += 1;
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

function loadCsv(name) {
  const p = resolve(TABLE_DIR, name);
  if (!existsSync(p)) return [];
  const raw = readFileSync(p, 'utf8').trim();
  if (!raw) return [];
  const rows = parseCsv(raw);
  if (rows.length < 2) return [];
  const header = rows[0].map((h) => String(h).replace(/^\uFEFF/, ''));
  return rows.slice(1).map((cols) => {
    const out = {};
    for (let i = 0; i < header.length; i += 1) {
      out[header[i]] = cols[i] ?? '';
    }
    return out;
  });
}

function toExportName(fileName) {
  const base = fileName.replace(/\.csv$/i, '');
  const camel = base.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
  return `${camel.replace(/^./, (c) => c.toUpperCase())}_FROM_BALANCE_CSV`;
}

function esc(s) {
  return JSON.stringify(String(s ?? ''));
}

function emitRowObject(row) {
  const keys = Object.keys(row);
  const fields = keys.map((k) => `${JSON.stringify(k)}: ${esc(row[k])}`).join(', ');
  return `{ ${fields} }`;
}

if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true });

const csvFiles = readdirSync(TABLE_DIR).filter((f) => f.endsWith('.csv'));
const exports = [];

for (const file of csvFiles.sort()) {
  const rows = loadCsv(file);
  const exportName = toExportName(file);
  const outFile = `csv${exportName.replace(/_FROM_BALANCE_CSV$/, '')}.ts`;
  const body = rows.map(emitRowObject).join(',\n  ');
  const ts = `// AUTO-GENERATED by tools/balance-tables/build-balance-from-csv.mjs
export const ${exportName} = [
  ${body}${rows.length ? ',' : ''}
] as const;
export type ${exportName.replace(/_FROM_BALANCE_CSV$/, 'Row')} = (typeof ${exportName})[number];
`;
  writeFileSync(resolve(OUT_DIR, outFile), ts, 'utf8');
  exports.push({ exportName, outFile: outFile.replace(/\.ts$/, '') });
}

const indexLines = [
  '// AUTO-GENERATED by tools/balance-tables/build-balance-from-csv.mjs',
  ...exports.map((e) => `export { ${e.exportName} } from './${e.outFile}';`),
  '',
];
writeFileSync(resolve(OUT_DIR, 'index.ts'), indexLines.join('\n'), 'utf8');
console.log(`Generated balance TS at src/data/balance/generated (${exports.length} tables)`);
