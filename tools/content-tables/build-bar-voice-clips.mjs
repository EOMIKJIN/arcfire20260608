/**
 * Table-First — 바 공연 보이스 클립 생성
 * 정본: tables/content/bar_voice_clips.csv
 * 전체 build:content-tables 의 음료 가격 sync 와 분리한다.
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(process.cwd());
const CSV_PATH = resolve(ROOT, 'tables', 'content', 'bar_voice_clips.csv');
const OUT_PATH = resolve(ROOT, 'src', 'data', 'generated', 'csvBarVoiceClips.ts');

function parseCsv(text) {
  const rows = [];
  let i = 0;
  let field = '';
  let row = [];
  let inQuotes = false;
  while (i < text.length) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 2;
          continue;
        }
        inQuotes = false;
      } else {
        field += ch;
      }
      i += 1;
      continue;
    }
    if (ch === '"') {
      inQuotes = true;
      i += 1;
      continue;
    }
    if (ch === ',') {
      row.push(field);
      field = '';
      i += 1;
      continue;
    }
    if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field);
      if (row.some((c) => String(c).trim() !== '')) rows.push(row);
      field = '';
      row = [];
      i += 1;
      continue;
    }
    field += ch;
    i += 1;
  }
  if (field.length || row.length) {
    row.push(field);
    if (row.some((c) => String(c).trim() !== '')) rows.push(row);
  }
  return rows;
}

function q(s) {
  return JSON.stringify(String(s ?? ''));
}

function toInt(v, fallback = 0) {
  const n = Number(v);
  return Number.isFinite(n) ? Math.floor(n) : fallback;
}

function normalizeRole(v) {
  return String(v ?? '').trim().toLowerCase() === 'dialog' ? 'dialog' : 'song';
}

function loadRows() {
  if (!existsSync(CSV_PATH)) throw new Error(`[bar-voice] missing ${CSV_PATH}`);
  const raw = readFileSync(CSV_PATH, 'utf8').replace(/^\uFEFF/, '');
  const matrix = parseCsv(raw);
  if (matrix.length < 2) return [];
  const headers = matrix[0].map((h) => h.trim());
  return matrix.slice(1).map((cells) => {
    const o = {};
    headers.forEach((h, idx) => {
      o[h] = cells[idx] ?? '';
    });
    return o;
  });
}

function main() {
  mkdirSync(resolve(ROOT, 'src', 'data', 'generated'), { recursive: true });
  const all = loadRows().filter((r) => String(r.enabled).trim() !== '0');
  const body = all
    .map(
      (r) => `  {
    clipId: ${q(r.clipId)},
    songId: ${q(r.songId)},
    role: ${q(normalizeRole(r.role))},
    assetKey: ${q(r.assetKey)},
    format: ${q(r.format)},
    durationMs: ${toInt(r.durationMs, 0)},
    bytes: ${toInt(r.bytes, 0)},
    loop: ${String(r.loop) === '1' || String(r.loop).toLowerCase() === 'true'},
    testClip: ${String(r.testClip) === '1' || String(r.testClip).toLowerCase() === 'true'},
    captionKo: ${q(r.captionKo)},
    captionEn: ${q(r.captionEn)},
    note: ${q(r.note)},
  }`,
    )
    .join(',\n');

  const content = `// AUTO-GENERATED by tools/content-tables/build-bar-voice-clips.mjs
/** Table-First 정본: tables/content/bar_voice_clips.csv */

export type BarVoiceClipRole = 'dialog' | 'song';

export type BarVoiceClipCsvRow = {
  clipId: string;
  /** 비면 해당 role 전 곡·전 종업원 폴백 */
  songId: string;
  role: BarVoiceClipRole;
  assetKey: string;
  format: string;
  durationMs: number;
  bytes: number;
  loop: boolean;
  testClip: boolean;
  captionKo: string;
  captionEn: string;
  note: string;
};

export const BAR_VOICE_CLIPS_FROM_CSV: readonly BarVoiceClipCsvRow[] = [
${body}
];
`;

  writeFileSync(OUT_PATH, content, 'utf8');
  console.log(`[bar-voice] clips=${all.length} -> ${OUT_PATH}`);
}

main();
