import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(process.cwd());
const TABLE_DIR = resolve(ROOT, 'tables', 'content');
const OUT_DIR = resolve(ROOT, 'src', 'data', 'generated');

function parseCsv(text) {
  const rows = [];
  let i = 0;
  let field = '';
  let row = [];
  let inQuotes = false;
  while (i < text.length) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 2;
          continue;
        }
        inQuotes = false;
      } else {
        field += ch;
      }
      i += 1;
      continue;
    }
    if (ch === '"') {
      inQuotes = true;
      i += 1;
      continue;
    }
    if (ch === ',') {
      row.push(field);
      field = '';
      i += 1;
      continue;
    }
    if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field);
      field = '';
      rows.push(row);
      row = [];
      i += 1;
      continue;
    }
    field += ch;
    i += 1;
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

function loadCsv(name) {
  const raw = readFileSync(resolve(TABLE_DIR, name), 'utf8').trim();
  const rows = parseCsv(raw);
  if (rows.length < 2) return [];
  const header = [...rows[0]];
  if (header[0]) header[0] = String(header[0]).replace(/^\uFEFF/, '');
  return rows.slice(1).map((cols) => {
    const out = {};
    for (let i = 0; i < header.length; i += 1) out[header[i]] = cols[i] ?? '';
    return out;
  });
}

function writeOut(fileName, exportName, rows) {
  const body = JSON.stringify(rows, null, 2);
  writeFileSync(
    resolve(OUT_DIR, fileName),
    `// AUTO-GENERATED by tools/content-tables/build-arc-core-chat-tables.mjs\nexport const ${exportName} = ${body} as const;\n`,
    'utf8',
  );
}

